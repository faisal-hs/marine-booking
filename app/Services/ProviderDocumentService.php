<?php

namespace App\Services;

use App\Models\Provider;
use App\Models\ProviderDocument;
use App\Repositories\Contracts\ProviderDocumentRepositoryInterface;
use Illuminate\Contracts\Filesystem\Filesystem;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\Storage;
use Illuminate\Validation\ValidationException;
use RuntimeException;
use Symfony\Component\HttpFoundation\StreamedResponse;

/**
 * Verification documents are evidence about a business, so they are kept on a
 * private disk and only ever read back through an authenticated route.
 */
class ProviderDocumentService
{
    public function __construct(protected ProviderDocumentRepositoryInterface $repository) {}

    public function upload(Provider $provider, UploadedFile $file, string $type, ?string $title): ProviderDocument
    {
        $limit = (int) config('providers.documents.max_per_provider');

        if ($this->repository->countForProvider($provider->id) >= $limit) {
            throw ValidationException::withMessages([
                'file' => ["You can keep at most {$limit} documents. Delete one before uploading another."],
            ]);
        }

        // The stored name is generated by the server, never taken from the upload, so
        // a hostile file name cannot influence where or how the file is stored.
        $path = $this->disk()->putFile("provider-documents/{$provider->uuid}", $file);

        if ($path === false) {
            throw new RuntimeException('The document could not be stored.');
        }

        return $this->repository->create([
            'provider_id' => $provider->id,
            'type' => $type,
            'title' => $title,
            'original_name' => $this->displayName($file),
            'path' => $path,
            'mime_type' => (string) $file->getMimeType(),
            'size_bytes' => (int) $file->getSize(),
        ]);
    }

    public function delete(ProviderDocument $document): void
    {
        // Once verified, the documents are the record that verification was based on.
        if ($document->provider->isVerified()) {
            throw ValidationException::withMessages([
                'document' => ['Documents of a verified provider cannot be removed, because they are the record the verification was based on.'],
            ]);
        }

        $this->disk()->delete($document->path);
        $this->repository->delete($document);
    }

    public function download(ProviderDocument $document): StreamedResponse
    {
        abort_unless($this->disk()->exists($document->path), 404);

        // Always an attachment, and never sniffed into another type by the browser.
        return $this->disk()->download($document->path, $document->original_name, [
            'X-Content-Type-Options' => 'nosniff',
        ]);
    }

    private function disk(): Filesystem
    {
        return Storage::disk(config('providers.documents.disk'));
    }

    /** A safe label for screens and download names: no path parts, no control characters. */
    private function displayName(UploadedFile $file): string
    {
        $name = preg_replace('/[^\pL\pN\s._-]+/u', '_', basename($file->getClientOriginalName()));
        $name = trim((string) $name);

        return $name === '' ? 'document' : mb_substr($name, 0, 200);
    }
}
